export const findCampaignLesson = (id: string): DuolingoLesson => {
  for (const unit of DUOLINGO_UNITS) {
    const found = unit.lessons.find((l) => l.id === id);
    if (found) return found;
  }
  const extraFound = EXTRA_LESSONS.find((l) => l.id === id);
  if (extraFound) return extraFound;
  return DUOLINGO_UNITS[0].lessons[0];
};

